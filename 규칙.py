"""팀 규칙(공고 2.3절, 2.4절, 2.5절)을 DB와 상관없이 따지는 순수 함수 모음."""

from dataclasses import dataclass

역할목록 = ("기획자", "웹 프로그래머", "프론트엔드 디자이너", "테스터", "보고서 작성자", "발표자")
필수역할 = ("기획자", "웹 프로그래머")
최소인원 = 2
최대인원 = 4


@dataclass(frozen=True)
class 학생:
    학번: str
    이름: str
    주역할: str
    보조역할: tuple = ()

    def 맡을수있는역할(self):
        return {self.주역할, *self.보조역할}

    def 표시(self):
        보조 = ", ".join(self.보조역할) if self.보조역할 else "없음"
        return f"{self.이름} (주 역할: {self.주역할}, 보조 역할: {보조})"


def 필수역할_최대배치(팀원들):
    """기획자와 웹 프로그래머를 서로 다른 팀원에게 맡길 때 최대 몇 자리를 채우는지 셉니다."""
    기획가능 = [i for i, 사람 in enumerate(팀원들) if "기획자" in 사람.맡을수있는역할()]
    웹가능 = [i for i, 사람 in enumerate(팀원들) if "웹 프로그래머" in 사람.맡을수있는역할()]
    if any(i != j for i in 기획가능 for j in 웹가능):
        return 2
    if 기획가능 or 웹가능:
        return 1
    return 0


def 못채운_필수역할수(팀원들):
    return len(필수역할) - 필수역할_최대배치(팀원들)


def 지원_검사(팀원들, 지원자):
    """지원자가 팀에 들어가도 되는지 따집니다. 막히면 그 이유를, 괜찮으면 None을 돌려줍니다.

    지원할 때와 모든 팀원이 찬성해 승인하기 직전에 똑같이 씁니다.
    """
    if len(팀원들) >= 최대인원:
        return "팀이 꽉 참"
    if any(사람.주역할 == 지원자.주역할 for 사람 in 팀원들):
        return "같은 주 역할의 팀원이 있음"
    새팀 = [*팀원들, 지원자]
    if 못채운_필수역할수(새팀) > 최대인원 - len(새팀):
        return "필수 포함 역할(기획자, 웹 프로그래머)을 맡을 학생의 자리가 모자람"
    return None


def 팀_검사(팀이름, 팀원들):
    """확정할 팀 하나가 규칙(인원, 주 역할 중복, 필수 포함 역할)을 지키는지 따져 문제 목록을 돌려줍니다."""
    문제들 = []
    if not 최소인원 <= len(팀원들) <= 최대인원:
        문제들.append(f"{팀이름}의 인원이 {len(팀원들)}명임(2~4명이어야 함)")
    주역할들 = [사람.주역할 for 사람 in 팀원들]
    for 역할 in sorted(set(주역할들)):
        if 주역할들.count(역할) > 1:
            문제들.append(f"{팀이름}에 주 역할이 {역할}인 학생이 {주역할들.count(역할)}명임")
    if 팀원들 and 필수역할_최대배치(팀원들) < len(필수역할):
        문제들.append(f"{팀이름}에 기획자와 웹 프로그래머를 서로 다른 학생으로 채울 수 없음")
    return 문제들


def 배정안_검사(팀별팀원, 팀이름들, 미배정, 배정):
    """배정안을 공고 2.5절 4항의 다섯 가지로 검사합니다. 문제가 없으면 빈 목록을 돌려줍니다.

    팀별팀원: {팀번호: [학생, ...]} 지금 팀원
    미배정: [학생, ...] 팀이 없는 학생
    배정: {학번: 팀번호} 팀이 없는 학생을 넣을 팀
    """
    문제들 = []
    미배정학번 = {사람.학번 for 사람 in 미배정}
    빠진학생 = 미배정학번 - set(배정)
    모르는학생 = set(배정) - 미배정학번
    if 빠진학생:
        문제들.append(f"배정되지 않은 학생이 있음({', '.join(sorted(빠진학생))})")
    if 모르는학생:
        문제들.append(f"팀이 없는 학생이 아닌 학번이 있음({', '.join(sorted(모르는학생))})")
    없는팀 = {팀 for 팀 in 배정.values() if 팀 not in 팀별팀원}
    if 없는팀:
        문제들.append(f"없는 팀 번호가 있음({', '.join(map(str, sorted(없는팀)))})")
    if 문제들:
        return 문제들

    학생찾기 = {사람.학번: 사람 for 사람 in 미배정}
    for 팀번호, 팀원들 in 팀별팀원.items():
        새팀 = [*팀원들, *(학생찾기[학번] for 학번, 팀 in 배정.items() if 팀 == 팀번호)]
        문제들.extend(팀_검사(팀이름들[팀번호], 새팀))
    return 문제들


def 배정_찾기(팀별팀원, 미배정):
    """규칙을 모두 지키는 배정을 모든 경우를 따져 찾습니다. 없으면 None을 돌려줍니다.

    이미 팀에 있는 학생은 옮기지 않고, 팀이 없는 학생만 넣습니다.
    """
    팀번호들 = sorted(팀별팀원)
    인원 = {팀: len(팀별팀원[팀]) for 팀 in 팀번호들}
    주역할들 = {팀: {사람.주역할 for 사람 in 팀별팀원[팀]} for 팀 in 팀번호들}
    새팀원 = {팀: list(팀별팀원[팀]) for 팀 in 팀번호들}

    def 후보팀(사람):
        return [팀 for 팀 in 팀번호들 if 인원[팀] < 최대인원 and 사람.주역할 not in 주역할들[팀]]

    # 갈 수 있는 팀이 적은 학생부터 넣어야 빨리 막다른 길을 알아챕니다.
    순서 = sorted(미배정, key=lambda 사람: len(후보팀(사람)))
    배정 = {}

    def 가능성_있음(남은수):
        if 남은수 > sum(최대인원 - 인원[팀] for 팀 in 팀번호들):
            return False
        if 남은수 < sum(max(0, 최소인원 - 인원[팀]) for 팀 in 팀번호들):
            return False
        return all(못채운_필수역할수(새팀원[팀]) <= 최대인원 - 인원[팀] for 팀 in 팀번호들)

    def 넣기(위치):
        if 위치 == len(순서):
            return all(not 팀_검사(str(팀), 새팀원[팀]) for 팀 in 팀번호들)
        사람 = 순서[위치]
        for 팀 in 후보팀(사람):
            배정[사람.학번] = 팀
            인원[팀] += 1
            주역할들[팀].add(사람.주역할)
            새팀원[팀].append(사람)
            if 가능성_있음(len(순서) - 위치 - 1) and 넣기(위치 + 1):
                return True
            새팀원[팀].pop()
            주역할들[팀].discard(사람.주역할)
            인원[팀] -= 1
            del 배정[사람.학번]
        return False

    if not 가능성_있음(len(순서)):
        return None
    return dict(배정) if 넣기(0) else None


def 배정불가_사유(팀별팀원, 팀이름들, 미배정):
    """규칙을 지키는 배정이 없을 때 관리자에게 보여 줄 이유를 만듭니다."""
    남은자리 = sum(최대인원 - len(팀원들) for 팀원들 in 팀별팀원.values())
    if len(미배정) > 남은자리:
        return f"팀이 없는 학생 {len(미배정)}명보다 남은 자리 {남은자리}개가 적음"
    모자란팀 = [팀 for 팀, 팀원들 in sorted(팀별팀원.items()) if len(팀원들) < 최소인원]
    필요인원 = sum(최소인원 - len(팀별팀원[팀]) for 팀 in 모자란팀)
    if len(미배정) < 필요인원:
        이름들 = ", ".join(팀이름들[팀] for 팀 in 모자란팀)
        return f"팀이 없는 학생 {len(미배정)}명으로는 2명이 안 되는 팀({이름들})을 채울 수 없음"
    for 팀, 팀원들 in sorted(팀별팀원.items()):
        팀주역할 = {사람.주역할 for 사람 in 팀원들}
        for 역할 in 필수역할:
            if any(역할 in 사람.맡을수있는역할() for 사람 in 팀원들):
                continue
            후보 = [사람 for 사람 in 미배정 if 역할 in 사람.맡을수있는역할() and 사람.주역할 not in 팀주역할]
            if not 후보 or len(팀원들) >= 최대인원:
                return f"{팀이름들[팀]}에 {역할}를 맡을 학생이 없음"
    return "모든 경우를 따져 봤지만 규칙(인원, 주 역할 중복, 필수 포함 역할)을 모두 지키는 배정이 없음"
