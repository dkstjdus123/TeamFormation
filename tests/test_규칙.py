"""규칙.py의 순수 함수 시험."""

from 규칙 import 학생, 배정_찾기, 배정불가_사유, 배정안_검사, 지원_검사, 필수역할_최대배치


def 사람(학번, 주역할, *보조):
    return 학생(학번, f"학생{학번}", 주역할, tuple(보조))


def test_한_학생이_두_필수역할을_다_해도_하나로만_센다():
    assert 필수역할_최대배치([사람("1", "기획자", "웹 프로그래머")]) == 1
    assert 필수역할_최대배치([사람("1", "기획자", "웹 프로그래머"), 사람("2", "테스터", "웹 프로그래머")]) == 2
    assert 필수역할_최대배치([사람("1", "테스터"), 사람("2", "발표자")]) == 0


def test_지원_검사_막힘_이유():
    기획 = 사람("1", "기획자")
    웹 = 사람("2", "웹 프로그래머")
    assert 지원_검사([기획], 사람("3", "기획자", "테스터")) == "같은 주 역할의 팀원이 있음"
    assert 지원_검사([기획, 웹, 사람("3", "테스터"), 사람("4", "발표자")], 사람("5", "보고서 작성자")) == "팀이 꽉 참"
    assert 지원_검사([기획, 웹], 사람("3", "테스터")) is None


def test_공고의_필수역할_자리_예시():
    # 주 역할이 기획자이고 보조 역할이 웹 프로그래머인 학생 혼자 있는 팀은 필수 역할 2개 가운데 1개만 채운 것.
    혼자 = [사람("1", "기획자", "웹 프로그래머")]
    assert 지원_검사(혼자, 사람("2", "테스터")) is None  # 남는 자리 2개 ≥ 못 채운 1개
    # 테스터와 발표자만 있는 팀에 보고서 작성자가 지원하면 남는 자리 1개로 2개를 채울 수 없으므로 막힘.
    팀 = [사람("1", "테스터"), 사람("2", "발표자")]
    assert "필수 포함 역할" in 지원_검사(팀, 사람("3", "보고서 작성자"))
    # 같은 팀이라도 기획자를 맡을 수 있는 학생은 들어갈 수 있음(남는 자리 1개로 웹 프로그래머 1개).
    assert 지원_검사(팀, 사람("3", "보고서 작성자", "기획자")) is None


def test_배정_찾기는_규칙을_지키는_배정을_찾는다():
    팀별 = {1: [사람("1", "기획자")], 2: [사람("2", "웹 프로그래머", "기획자")], 3: []}
    미배정 = [
        사람("3", "웹 프로그래머"),
        사람("4", "기획자", "테스터"),
        사람("5", "테스터", "웹 프로그래머"),
        사람("6", "발표자"),
        사람("7", "보고서 작성자", "기획자"),
    ]
    이름들 = {1: "팀1", 2: "팀2", 3: "팀3"}
    배정 = 배정_찾기(팀별, 미배정)
    assert 배정 is not None
    assert 배정안_검사(팀별, 이름들, 미배정, 배정) == []


def test_배정이_없으면_None과_이유():
    팀별 = {1: [사람("1", "테스터"), 사람("2", "발표자")], 2: [사람("3", "기획자"), 사람("4", "웹 프로그래머")]}
    미배정 = [사람("5", "보고서 작성자")]
    이름들 = {1: "팀1", 2: "팀2"}
    assert 배정_찾기(팀별, 미배정) is None
    assert 배정불가_사유(팀별, 이름들, 미배정) == "팀1에 기획자를 맡을 학생이 없음"


def test_배정안_검사가_다섯_가지를_따진다():
    팀별 = {1: [사람("1", "기획자"), 사람("2", "웹 프로그래머")], 2: []}
    이름들 = {1: "팀1", 2: "팀2"}
    미배정 = [사람("3", "테스터"), 사람("4", "테스터")]
    assert any("배정되지 않은" in 문제 for 문제 in 배정안_검사(팀별, 이름들, 미배정, {"3": 1}))
    문제들 = 배정안_검사(팀별, 이름들, 미배정, {"3": 1, "4": 1})
    assert any("주 역할이 테스터인 학생이 2명" in 문제 for 문제 in 문제들)
    assert any("팀2의 인원이 0명" in 문제 for 문제 in 문제들)
    문제들 = 배정안_검사(팀별, 이름들, 미배정, {"3": 1, "4": 2})
    assert any("팀2의 인원이 1명" in 문제 for 문제 in 문제들)
