"""공고 부록의 연습용 시나리오 3개를 서비스 함수로 끝까지 해 보고, 단계마다 결과 안내의 첫 단어를 확인합니다.

AI 키를 주지 않으므로 배정은 3차 모델까지 실패한 뒤 앱이 스스로 배정하는 길로 갑니다.
"""

import pytest

import 서비스
from conftest import 명단폴더
from 규칙 import 팀_검사


def 올리기(풀, 파일, 팀수):
    결과 = 서비스.명단_올리기(풀, (명단폴더 / 파일).read_bytes(), 팀수)
    assert 결과.startswith("승인"), 결과
    상태 = 서비스.상태_읽기(풀)
    # 이름 "학생3(PL;TT)"의 "학생3"으로 학번을 찾습니다.
    return {사람.이름.split("(")[0]: 학번 for 학번, 사람 in 상태.학생들.items()}


def 첫단어(결과):
    return 결과.split(":")[0]


class 진행:
    def __init__(self, 풀, 학번표):
        self.풀, self.학번 = 풀, 학번표

    def 지원(self, 이름, 팀, 기대):
        결과 = 서비스.지원하기(self.풀, self.학번[이름], 팀)
        assert 첫단어(결과) == 기대, f"{이름} → 팀{팀}: {결과}"

    def 투표(self, 투표자, 지원자, 찬성, 기대):
        결과 = 서비스.투표하기(self.풀, self.학번[투표자], self.학번[지원자], 찬성)
        assert 첫단어(결과) == 기대, f"{투표자} → {지원자}: {결과}"

    def 마감_배정_확정(self):
        assert 서비스.모집_마감(self.풀).startswith("승인")
        결과, 안내 = 서비스.AI_배정(self.풀, "", ["모델1", "모델2", "모델3"])
        assert 결과.startswith("승인"), (결과, 안내)
        assert "앱이 직접" in 결과
        assert 서비스.배정_확정(self.풀).startswith("승인")
        상태 = 서비스.상태_읽기(self.풀)
        assert 상태.미배정() == []
        for 팀 in 상태.팀들:
            assert 팀_검사(팀["이름"], 상태.팀별팀원()[팀["번호"]]) == []
        return 상태


def test_쉬움(풀):
    진 = 진행(풀, 올리기(풀, "쉬움.csv", 3))
    진.지원("학생1", 1, "승인")
    진.지원("학생2", 2, "승인")
