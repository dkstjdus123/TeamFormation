def test_관리자는_명단을_다시_올려도_남는다(풀):
    서비스.관리자_준비(풀, "시험용비번")
    올리기(풀, "쉬움.csv", 3)
    assert 서비스.로그인(풀, "admin", "시험용비번")["관리자"] is True
    assert 서비스.로그인(풀, "admin", "틀림") is None
    서비스.관리자_준비(풀, "새비번")
    assert 서비스.로그인(풀, "admin", "시험용비번") is None
    assert 서비스.로그인(풀, "admin", "새비번")["관리자"] is True
    assert 서비스.로그인(풀, "2026101", "1234")["관리자"] is False
    assert 서비스.로그인(풀, "2026101", "") is None


