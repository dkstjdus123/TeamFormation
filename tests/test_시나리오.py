def test_막힘_경우들(풀):
    진 = 진행(풀, 올리기(풀, "쉬움.csv", 3))
    진.지원("학생1", 1, "승인")
    진.지원("학생1", 2, "막힘")  # 이미 팀이 있음
    진.지원("학생4", 1, "대기")
    진.지원("학생4", 2, "막힘")  # 결과를 기다리는 지원
    진.투표("학생1", "학생4", True, "승인")
    진.투표("학생1", "학생4", True, "막힘")  # 이미 끝난 지원
    진.지원("학생7", 1, "대기")
    진.투표("학생2", "학생7", True, "막힘")  # 다른 팀 학생은 투표 못 함
    진.투표("학생1", "학생7", True, "대기")
    진.투표("학생1", "학생7", False, "막힘")  # 투표는 바꿀 수 없음
    assert 서비스.배정_확정(풀).startswith("막힘")  # 마감 전
    assert 서비스.AI_배정(풀, "", ["a", "b", "c"])[0].startswith("막힘")


